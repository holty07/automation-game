import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { load } from '../../src/sim/serialise'
import { tick } from '../../src/sim/tick'
import { textDump } from '../../src/debug/textDump'

describe('empty world scenario', () => {
  it('matches the expected text dump after 100 ticks', () => {
    const json = readFileSync(new URL('../fixtures/empty-world.json', import.meta.url), 'utf8')
    const state = load(json)

    for (let i = 0; i < 100; i += 1) {
      tick(state)
    }

    expect(textDump(state)).toMatchInlineSnapshot(`
      "tick: 100
      grid:
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      ................
      entities:
        (none)
      bots:
        (none)"
    `)
  })
})
